/**
 * Given a BCP-47 tag like "bs-BA", return the country code "ba" for flags.
 * Falls back to matching by the language subtag alone.
 */
export function countryFromBcp47(tag: string): string | null {
  const parts = tag.split("-");
  const region = parts[1]?.toLowerCase();
  if (region && COUNTRIES.some((c) => c.code === region)) return region;
  const lang = parts[0].toLowerCase();
  return COUNTRIES.find((c) => c.lang === lang)?.code ?? null;
}
