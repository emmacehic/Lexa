/**
 * Copies the flag SVGs Lexa actually uses into public/flags/4x3 so the UI can
 * render them with <img> tags (reliable in Next.js; CSS background URLs can
 * fail for some regional flags depending on the bundler).
 */
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

import { COUNTRIES } from "../lib/countries";

const require = createRequire(import.meta.url);
const pkgRoot = dirname(require.resolve("flag-icons/package.json"));
const srcDir = join(pkgRoot, "flags/4x3");
const destDir = join(process.cwd(), "public/flags/4x3");

const LANGUAGE_FLAG: Record<string, string> = {
  af: "za", am: "et", ar: "arab", as: "in", az: "az", ba: "ru", be: "by", bg: "bg",
  bn: "bd", bo: "cn", br: "fr", bs: "ba", ca: "es-ct", cs: "cz", cy: "gb-wls", da: "dk",
  de: "de", el: "gr", en: "gb", es: "es", et: "ee", eu: "es-pv", fa: "ir", fi: "fi", fo: "fo",
  fr: "fr", gl: "es", gu: "in", ha: "ng", haw: "us", he: "il", hi: "in", hr: "hr", ht: "ht",
  hu: "hu", hy: "am", id: "id", is: "is", it: "it", ja: "jp", jw: "id", ka: "ge", kk: "kz",
  km: "kh", kn: "in", ko: "kr", la: "eu", lb: "lu", ln: "cd", lo: "la", lt: "lt", lv: "lv",
  mg: "mg", mi: "nz", mk: "mk", ml: "in", mn: "mn", mr: "in", ms: "my", mt: "mt", my: "mm",
  ne: "np", nl: "nl", nn: "no", no: "no", oc: "fr", pa: "in", pl: "pl", ps: "af", pt: "pt",
  ro: "ro", ru: "ru", sa: "in", sd: "pk", si: "lk", sk: "sk", sl: "si", sn: "zw", so: "so",
  sq: "al", sr: "rs", su: "id", sv: "se", sw: "tz", ta: "lk", te: "in", tg: "tj", th: "th",
  tk: "tm", tl: "ph", tr: "tr", tt: "ru", uk: "ua", ur: "pk", uz: "uz", vi: "vn", yi: "il",
  yo: "ng", zh: "cn",
};

const needed = new Set<string>(["un", ...Object.values(LANGUAGE_FLAG), ...COUNTRIES.map((c) => c.code)]);

mkdirSync(destDir, { recursive: true });

const available = new Set(
  readdirSync(srcDir)
    .filter((name) => name.endsWith(".svg"))
    .map((name) => name.replace(/\.svg$/, "")),
);

const missing: string[] = [];
for (const code of needed) {
  if (!available.has(code)) {
    missing.push(code);
    continue;
  }
  copyFileSync(join(srcDir, `${code}.svg`), join(destDir, `${code}.svg`));
}

if (!available.has("un")) {
  throw new Error("flag-icons is missing the UN fallback flag (un.svg).");
}
copyFileSync(join(srcDir, "un.svg"), join(destDir, "un.svg"));

const codesTs = `/** Generated by scripts/sync-flag-assets.ts — do not edit by hand. */\nexport const FLAG_ICON_CODES = new Set<string>([\n${[...needed]
  .filter((code) => available.has(code))
  .sort()
  .map((code) => `  ${JSON.stringify(code)},`)
  .join("\n")}\n]);\n`;

writeFileSync(join(process.cwd(), "lib/flag-icon-codes.ts"), codesTs);

if (missing.length > 0) {
  console.warn("Skipped missing flag-icons assets:", missing.join(", "));
}

console.log(`Synced ${needed.size - missing.length} flags to public/flags/4x3`);
